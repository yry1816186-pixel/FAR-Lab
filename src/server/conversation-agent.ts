const makeListRuns = (app: App): AgentTool => ({
  name: 'list_runs',
  description: 'List research runs in this workspace (newest first): id, status, current stage, creation time, and the research question.',
  inputSchema: z.object({ limit: z.number().int().min(1).max(30).default(10) }),
  riskClass: 'read',
  async execute(args): Promise<ToolResult> {
    const { limit } = z.object({ limit: z.number().int().min(1).max(30).default(10) }).parse(args);
    const rows = app.store.listRuns(limit).map((r) => {
      const run = app.store.getRun(r.id);
      const question = run !== null ? app.store.getObject('question', run.questionId) : null;
      return {
        id: r.id, status: r.status, currentStage: r.currentStage, createdAt: r.createdAt,
        question: question !== null ? head(question.text, 160) : null,
      };
    });
    return { ok: true, data: { runs: rows }, summary: `${rows.length} runs` };
  },
});

const makeGetRunDetails = (app: App): AgentTool => ({
  name: 'get_run_details',
  description: 'One run\'s real state: question, stage progression, hypothesis/evidence/source counts, top hypotheses with their claim balance, revision and experiment counts.',
  inputSchema: z.object({ runId: z.string().min(1).max(64) }),
  riskClass: 'read',
  async execute(args): Promise<ToolResult> {
    const { runId } = z.object({ runId: z.string().min(1).max(64) }).parse(args);
    const run = app.store.getRun(runId);
    if (run === null) return { ok: false, error: { kind: 'validation', message: `run not found: ${runId}` } };
    const question = app.store.getObject('question', run.questionId);
    const hypotheses = app.store.listObjects('hypothesis', runId);
    const claims = app.store.listObjects('claim', runId);
    const relations = app.store.listObjects('evidence_relation', runId);
    const sources = app.store.listObjects('source_document', runId);
    return {
      ok: true,
      data: {
        id: run.id, status: run.status, currentStage: run.currentStage,
        createdAt: run.createdAt, updatedAt: run.updatedAt,
        question: question !== null ? head(question.text, 300) : null,
        stages: run.stages.map((s) => ({ stage: s.stage, state: s.state })),
        counts: {
          hypotheses: hypotheses.length, claims: claims.length,
          evidenceRelations: relations.length, sourceDocuments: sources.length,
          revisions: app.store.listObjects('revision', runId).length,
          experimentRuns: app.store.listObjects('experiment_run', runId).length,
        },
        topHypotheses: hypotheses.slice(0, 5).map((h) => ({
          id: h.id, statement: head(h.statement, 200), mechanism: head(h.mechanism, 120),
          supportingClaims: h.supportingClaimIds.length, counterClaims: h.counterClaimIds.length,
        })),
      },
      summary: `run ${run.id.slice(0, 10)} ${run.status}`,
    };
  },
});

const makeGetRunPlan = (app: App): AgentTool => ({
  name: 'get_run_plan',
  description: 'The run\'s latest research plan (goal, stages, key actions) as a bounded excerpt. An absent plan is an honest finding.',
  inputSchema: z.object({ runId: z.string().min(1).max(64) }),
  riskClass: 'read',
  summarize: (payload) => {
    const p = payload as { plan?: unknown; note?: string };
    return p.plan !== null && p.plan !== undefined ? 'plan excerpt' : String(p.note ?? 'no plan');
  },
  async execute(args): Promise<ToolResult> {
    const { runId } = z.object({ runId: z.string().min(1).max(64) }).parse(args);
    if (app.store.getRun(runId) === null) return { ok: false, error: { kind: 'validation', message: `run not found: ${runId}` } };
    const plan = app.store.listObjects('plan', runId).at(-1) ?? null;
    if (plan === null) return { ok: true, data: { plan: null, note: 'this run has no plan yet (still early-stage or not generated)' }, summary: 'no plan' };
    const serialized = JSON.stringify(plan);
    return {
      ok: true,
      data: { planId: plan.id, excerpt: serialized.slice(0, 4000), truncated: serialized.length > 4000 },
      summary: `plan ${plan.id.slice(0, 10)}`,
    };
  },
});

const makeSearchWorkspace = (app: App): AgentTool => ({
  name: 'search_workspace',
  description: 'Full-text search across this workspace\'s research questions, hypotheses and claims (bm25-ranked, CJK-aware). Empty results are honest findings.',
  inputSchema: z.object({ query: z.string().min(2).max(200) }),
  riskClass: 'read',
  async execute(args): Promise<ToolResult> {
    const { query } = z.object({ query: z.string().min(2).max(200) }).parse(args);
    const hits = app.store.searchText(query, { questions: 5, hypotheses: 8, claims: 8 });
    const trim = (rows: typeof hits.questions) => rows.map((h) => ({ runId: h.runId, id: h.id, text: head(h.text, 200) }));
    return {
      ok: true,
      data: { questions: trim(hits.questions), hypotheses: trim(hits.hypotheses), claims: trim(hits.claims) },
      summary: `${hits.questions.length + hits.hypotheses.length + hits.claims.length} hits`,
    };
  },
});

const makeWorkspaceStatus = (app: App): AgentTool => ({
  name: 'workspace_status',
  description: 'Workspace overview: run counts by status, in-flight runs with current stage, conversation count, enabled automations, and the active model config id.',
  inputSchema: z.object({}),
  riskClass: 'read',
  async execute(): Promise<ToolResult> {
    const runs = app.store.listRuns(200);
    const byStatus: Record<string, number> = {};
    for (const r of runs) byStatus[r.status] = (byStatus[r.status] ?? 0) + 1;
    const automations = app.store.listObjects('automation', '__none__');
    const activeModel = app.store.getMeta('active_model_config');
    return {
      ok: true,
      data: {
        runsTotal: runs.length,
        runsByStatus: byStatus,
        inFlight: runs.filter((r) => r.status === 'running' || r.status === 'queued')
          .slice(0, 10).map((r) => ({ id: r.id, stage: r.currentStage })),
        conversations: app.store.listObjects('conversation', '__none__').length,
        automations: { total: automations.length, enabled: automations.filter((a) => a.enabled).length },
        activeModelConfigId: activeModel,
      },
      summary: `${runs.length} runs`,
    };
  },
});

// ---- propose_action: records a pending approval card; NEVER executes in-loop ----

const seedDigest = (seeds: readonly ConversationSeed[] | undefined): string[] =>
  (seeds ?? []).slice(0, 12).map((s) => {
    const ident = s.identifiers[0];
    return `- ${s.title}${s.year !== undefined ? ` (${s.year})` : ''}${ident !== undefined ? ` [${ident.kind}:${ident.value}]` : ''}${s.text !== undefined ? ` · 全文已提供(${s.text.length}字符)` : ''}`;
  });

const makeProposeAction = (app: App, conv: Conversation, proposals: ConversationProposal[]): AgentTool => ({
  name: 'propose_action',
  description: 'Propose a concrete action as an approval card for the researcher: launch_research (start a run carrying ALL conversation materials), create_automation (standing agent task on schedule or on run completion), cancel_automation, create_tool_integration (stage a tool config — MCP server / skill / command / hook rule — from a draft; stored DISABLED, the researcher activates it in settings). Records the proposal — execution happens only after approval.',
  inputSchema: z.object({
    kind: z.enum(['launch_research', 'create_automation', 'cancel_automation', 'create_tool_integration']),
    title: z.string().min(1).max(300),
    args: z.record(z.string(), z.unknown()),
  }),
  riskClass: 'read', // records a card only; execution is researcher-gated outside the loop
  async execute(args): Promise<ToolResult> {
    const parsed = z.object({
      kind: z.enum(['launch_research', 'create_automation', 'cancel_automation', 'create_tool_integration']),
      title: z.string().min(1).max(300),
      args: z.record(z.string(), z.unknown()),
    }).parse(args);
    if (proposals.length >= 10) {
      return { ok: false, error: { kind: 'validation', message: 'this turn already holds 10 proposals — finish and let the researcher resolve them first' } };
    }
    const argCheck = ACTION_ARG_SCHEMAS[parsed.kind].safeParse(parsed.args);
    if (!argCheck.success) {
      return { ok: false, error: { kind: 'validation', message: `invalid args for ${parsed.kind}: ${argCheck.error.issues.map((i) => `${i.path.join('.') || '(root)'}: ${i.message}`).slice(0, 3).join('; ')}` } };
    }
    if (parsed.kind === 'cancel_automation') {
      const cancel = CancelAutomationArgsSchema.parse(parsed.args);
      const target = app.store.getObject('automation', cancel.automationId);
      if (target === null) return { ok: false, error: { kind: 'validation', message: `automation not found: ${cancel.automationId}` } };
      if (target.conversationId !== conv.id) return { ok: false, error: { kind: 'validation', message: 'that automation belongs to a different conversation' } };
    }
    const autoApproved = conv.autoApprove.includes(parsed.kind);
    // RU-3 T6: server-computed disclosure — the model cannot forge risk level
    // or arg rendering; the card's title stays explicitly model-authored.
    const RISK_BY_KIND: Record<typeof parsed.kind, 'low' | 'moderate' | 'high'> = {
      launch_research: 'moderate',
      create_automation: 'moderate',
      cancel_automation: 'low',
      create_tool_integration: 'high',
    };
    const renderArgs = (kind: typeof parsed.kind, a: Record<string, unknown>): Record<string, string> => {
      const s = (v: unknown, max = 160): string => String(v ?? '').slice(0, max);
      switch (kind) {
        case 'launch_research':
          return { question: s(a.question), seeds: s((a.seedTexts as unknown[] | undefined)?.length ?? 0) };
        case 'create_automation':
          return { task: s(a.task), trigger: s(a.schedule ?? a.onRunCompleted) };
        case 'cancel_automation':
          return { automationId: s(a.automationId) };
        case 'create_tool_integration':
          return { toolType: s((a.draft as { toolType?: string } | undefined)?.toolType), label: s((a.draft as { label?: string } | undefined)?.label) };
      }
    };
    const proposal: ConversationProposal = {
      id: newId('act'),
      kind: parsed.kind,
      title: parsed.title,
      args: argCheck.data as Record<string, unknown>,
      status: 'pending',
      riskLevel: RISK_BY_KIND[parsed.kind],
      argSummary: renderArgs(parsed.kind, argCheck.data as Record<string, unknown>),
      ...(autoApproved ? { autoApproved: true } : {}),
      createdAt: new Date().toISOString(),
    };
    proposals.push(proposal);
    return {
      ok: true,
      data: {
        proposalId: proposal.id,
        state: autoApproved
          ? 'pre-approved for this conversation (remembered grant) — will execute when this turn completes'
          : 'awaiting researcher approval — tell the researcher what you proposed and why',
      },
      summary: `proposed ${parsed.kind}`,
    };
  },
});

// ---- the turn ----

/**
 * R2-13 F-5 fix: the conversation kernel's allow-expansion is keyed on the
 * registry's own risk class, not on registry membership. Read-class tools pass
 * (including propose_action — it only records an approval card; execution is
 * researcher-gated outside the loop). Anything else — an execute/edit-class
 * tool registered by a future kernel evolution — gets NO allow rule and falls
 * to the engine's fail-closed default instead of silently inheriting one.
 */
export const conversationAllowRules = (tools: ToolRegistry): Array<{ tool: string; effect: 'allow' }> =>
  tools.names()
    .filter((name) => tools.get(name)?.riskClass === 'read')
    .map((name) => ({ tool: name, effect: 'allow' as const }));

export async function generateConversationTurn(
  app: App,
  provider: ModelProvider,
  conv: Conversation,
  input: ConversationTurnInput,
): Promise<ConversationTurnGeneration> {
  const proposals: ConversationProposal[] = [];
  const toolTrace: ToolTrace[] = [];
  const tools = new ToolRegistry()
    .register(makeListRuns(app))
    .register(makeGetRunDetails(app))
    .register(makeGetRunPlan(app))
    .register(makeSearchWorkspace(app))
    .register(makeWorkspaceStatus(app))
    .register(makeProposeAction(app, conv, proposals));
  const permissions = new PermissionEngine({
    rules: conversationAllowRules(tools),
    defaultEffect: 'deny',
  });

  // Aggregating receipt collector (documented decision: conversation turns keep
  // usage on the message; full provenance receipts start when a run is launched).
  let usageModelCalls = 0;
  let usageLatencyMs = 0;
  let usagePromptTokens = 0;
  let usageCompletionTokens = 0;
  let sawTokens = false;
  let lastProvider = provider.name;
  let lastModelId = 'unknown';
  const recordReceipt: ReceiptSink = (partial) => {
    if (partial.kind !== 'model_call' || partial.modelCall === undefined) return;
    const mc = partial.modelCall;
    usageModelCalls += 1;
    usageLatencyMs += mc.latencyMs;
    lastProvider = mc.provider;
    lastModelId = mc.modelId;
    if (mc.usage.promptTokens !== undefined || mc.usage.completionTokens !== undefined) {
      sawTokens = true;
      usagePromptTokens += mc.usage.promptTokens ?? 0;
      usageCompletionTokens += mc.usage.completionTokens ?? 0;
    }
  };

  const emit: AgentEventSink = (ev) => {
    if (ev.type === 'tool_used') {
      toolTrace.push({
        tool: ev.tool, ok: ev.ok,
        ...(ev.summary !== undefined ? { summary: ev.summary.slice(0, 300) } : {}),
        durationMs: ev.durationMs,
      });
    }
  };

  const telemetry = new SessionTelemetry();
  const history = input.history;
  const materials = history
    .filter((m) => m.role === 'researcher' && (m.seeds?.length ?? 0) > 0)
    .flatMap((m) => seedDigest(m.seeds));
  const priorCandidates = history
    .filter((m) => m.role === 'agent' && (m.candidates?.length ?? 0) > 0)
    .flatMap((m) => (m.candidates ?? []).map((c) => `- ${c.text}`));
  const pendingProposals = history
    .flatMap((m) => m.proposals ?? [])
    .filter((p) => p.status === 'pending')
    .map((p) => `- ${p.kind}: ${p.title}`);
  const launchedRuns = conv.runIds.length > 0
    ? conv.runIds.slice(-10).map((id) => {
      const run = app.store.getRun(id);
      return run === null ? `- ${id} (not found)` : `- ${id} ${run.status} @ ${run.currentStage}`;
    })
    : [];

  const task = input.source === 'researcher'
    ? `研究者发来新消息：「${input.text}」\n回应它——需要工作区事实时先用工具核实，需要行动时用 propose_action 提案，然后 finish 给出最终回复。`
    : input.text; // automation trigger notice already carries its task

  const res = await runAgentLoop(
    {
      capability: 'conversation-resident',
      systemPrompt: RESIDENT_SYSTEM_PROMPT,
      task,
      maxTurns: input.maxTurns ?? 8,
      resultSchema: ConversationAgentReplySchema,
      contextEntries: [
        {
          label: 'conversation',
          payload: {
            id: conv.id, title: conv.title, status: conv.status,
            rememberedAutoApprove: conv.autoApprove.length > 0 ? conv.autoApprove : '（无——所有行动都需要批准）',
            launchedRuns: launchedRuns.length > 0 ? launchedRuns : '（本对话尚未启动研究）',
          },
        },
        {
          label: 'transcript_window',
          payload: history.map((m) => ({
            role: m.role,
            text: head(m.content, 1200),
            ...(m.candidates !== undefined && m.candidates.length > 0 ? { proposedCandidates: m.candidates.map((c) => c.text) } : {}),
            ...(m.proposals !== undefined && m.proposals.length > 0 ? { proposalsThisTurn: m.proposals.map((p) => `${p.kind}(${p.status})`) } : {}),
          })),
        },
        { label: 'materials_provided', payload: materials.length > 0 ? materials : '（研究者尚未提供材料）' },
        { label: 'prior_candidate_questions', payload: priorCandidates.length > 0 ? priorCandidates : '（尚未提出候选问题）' },
        { label: 'proposals_awaiting_approval', payload: pendingProposals.length > 0 ? pendingProposals : '（无等待中的提案）' },
        ...(input.seeds.length > 0 ? [{ label: 'new_materials', payload: seedDigest(input.seeds) }] : []),
      ],
    },
    {
      provider,
      tools,
      permissions,
      sessionId: newId('ags'),
      purpose: 'conversation:turn',
      ...(input.reasoning !== undefined ? { reasoning: input.reasoning } : {}),
      emit,
      recordReceipt,
      telemetry,
    },
  );

  const tel = telemetry.summary();
  const usage: ConversationTurnUsage | undefined = usageModelCalls > 0 ? {
    provider: lastProvider,
    modelId: lastModelId,
    latencyMs: usageLatencyMs,
    modelCalls: usageModelCalls,
    toolCalls: tel.toolCalls,
    ...(sawTokens ? { inputTokens: usagePromptTokens, outputTokens: usageCompletionTokens } : {}),
  } : undefined;

  return {
    status: res.status,
    ...(res.status === 'completed' && res.result !== undefined
      ? { reply: ConversationAgentReplySchema.parse(res.result) }
      : { error: res.error ?? `agent loop ended with status ${res.status}` }),
    toolTrace,
    ...(usage !== undefined ? { usage } : {}),
    proposals,
  };
}
