/**
 * Resident agent turn (PROPOSAL-resident-agent R1/R2): one conversation reply
 * generated by the REAL agent kernel (tool-using loop) — not a single blind
 * structured call. The agent can inspect the whole workspace through read
 * tools (runs / hypotheses / evidence / plans / search / status) and propose
 * actions; proposals NEVER execute inside the loop — they persist as pending
 * cards resolved by the researcher (or by a remembered per-conversation
 * grant) after the turn lands. Receipt discipline follows the conversation
 * doc: full provenance receipts stay run-scoped; here every model call is
 * AGGREGATED into the message usage summary (provider/model/tokens/counts).
 */

export const ConversationAgentReplySchema = z.object({
  reply: z.string().min(1),
  clarifyingQuestions: z.array(z.string().min(1).max(500)).max(3),
  candidates: z.array(z.object({
    text: z.string().min(1).max(2000),
    rationale: z.string().min(1).max(2000),
  })).max(5),
  readyToConverge: z.boolean(),
});
export type ConversationAgentReply = z.infer<typeof ConversationAgentReplySchema>;

/** Args contracts for the proposable action kinds (validated before a card is created). */
export const LaunchResearchArgsSchema = z.object({ question: z.string().min(10).max(2000) });
export const CreateAutomationArgsSchema = z.object({
  label: z.string().min(1).max(120).optional(),
  trigger: z.discriminatedUnion('kind', [
    z.object({ kind: z.literal('run_completed') }),
    z.object({ kind: z.literal('schedule'), intervalMinutes: z.number().int().min(1).max(20160) }),
  ]),
  task: z.string().min(10).max(2000),
});
export const CancelAutomationArgsSchema = z.object({ automationId: z.string().regex(/^auto_[a-z0-9]+$/) });

// TIS T4: tool-config drafting args live with the tool-integration domain
// (single owner); re-exported here so action-arg imports stay one-sided.
export { CreateToolIntegrationArgsSchema };

const ACTION_ARG_SCHEMAS = {
  launch_research: LaunchResearchArgsSchema,
  create_automation: CreateAutomationArgsSchema,
  cancel_automation: CancelAutomationArgsSchema,
  create_tool_integration: CreateToolIntegrationArgsSchema,
} as const;
export type ProposalKind = keyof typeof ACTION_ARG_SCHEMAS;

export interface ConversationTurnInput {
  /** The researcher's new message, or (source='automation') the trigger notice text. */
  text: string;
  seeds: ConversationSeed[];
  /** Transcript window chosen by the caller (token budget control). */
  history: ConversationMessage[];
  source: 'researcher' | 'automation';
  /** Turn ceiling for the kernel loop (default 8; automations pass their own cap). */
  maxTurns?: number;
  /**
   * Reasoning effort for this turn's model calls, resolved by the CALLER
   * (conversations.ts effectiveConversationReasoning — kept out of this module to
   * avoid an import cycle). Absent/undefined = nothing is sent on the wire.
   */
  reasoning?: { style: 'reasoning_effort' | 'enable_thinking' | 'thinking_budget'; gear: 'low' | 'medium' | 'high' };
}

export interface ConversationTurnUsage {
  provider: string;
  modelId: string;
  latencyMs: number;
  inputTokens?: number;
  outputTokens?: number;
  modelCalls: number;
  toolCalls: number;
}

export interface ConversationTurnGeneration {
  status: AgentLoopStatus;
  reply?: ConversationAgentReply;
  toolTrace: ToolTrace[];
  usage?: ConversationTurnUsage;
  proposals: ConversationProposal[];
  error?: string;
}

const head = (s: string, n: number): string => (s.length <= n ? s : `${s.slice(0, n)}…`);

const RESIDENT_SYSTEM_PROMPT = `你是 FAR-Lab 研究工作区的常驻 Agent——研究者通过对话与你讨论这个工作区的任何内容、向你布置工作。你运行在带工具的循环里：每一轮要么调用一个工具，要么给出最终回复。

职责与行为：
- 全域视野：用工具核实工作区事实（runs/假设/证据/计划/检索/状态），绝不在没有工具结果支撑时编造工作区内容、数字或文献。工具空结果是诚实发现，如实报告，不要换着花样重复查询。
- 研究前引导：当研究者还在塑形研究问题时，像敏锐的同行一样追问模糊概念、要求澄清变量与机制、指出被忽略的角度与对立解释，主动给出不同方向的候选问题（candidates）。
- 研究后讨论：run 已存在时，先读它的假设/证据/计划再评论；指出证据缺口、反例方向、下一步该做什么。
- 行动提案：研究者要求做事（启动研究、建自动化、停自动化、接入工具）时，用 propose_action 提案——它会生成一张需要研究者批准的卡片；本对话已记住"不再询问"的种类会在回合结束后自动执行。不要重复提案已经在等待批准的同类行动。研究者想接入外部工具（MCP 服务器、技能、命令、钩子规则）时，用 create_tool_integration 起草配置并说明理由与注意事项（如需要安装的依赖、密钥要研究者自己填）；起草的配置一律以停用状态入库，由研究者在设置中审查启用。
- 材料优先：研究者提供的文献/材料是唯一可引用的文献事实来源——绝不允许编造文献、数据或结论；没有材料或工具支撑的推断要明确标注"待验证"。
- 诚实：不知道就说不确定；工具失败就如实说明。用研究者的语言回复（中文提问则中文）。
- 精炼：每轮最终回复一般不超过 300 字，像对话而不是报告；讨论足够聚焦或研究者要求时才给 candidates 并把 readyToConverge 设为 true。

最终回复契约（finish 的 result 字段）：
{"reply": "<给研究者看的回复（markdown，可含简短列表）>", "clarifyingQuestions": ["<最多3个本轮追问，可空数组>"], "candidates": [{"text": "<候选研究问题，一句可检验的问句>", "rationale": "<为何值得做：已知/未知/价值>"], "readyToConverge": true|false}`;

